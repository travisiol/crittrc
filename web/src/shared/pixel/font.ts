/**
 * A boolean matrix for a whole string, one cell per art pixel.
 * `tracking` is the gap between glyphs, in pixels.
 */
export function textMatrix(text: string, tracking = 1): boolean[][] {
  const chars = [...text.toUpperCase()].map((c) => G[c] ?? G["?"]);
  const width = chars.length === 0 ? 0 : chars.length * GLYPH_W + (chars.length - 1) * tracking;
  const rows: boolean[][] = Array.from({ length: GLYPH_H }, () => new Array<boolean>(width).fill(false));
  let x = 0;
  for (const glyph of chars) {
    for (let y = 0; y < GLYPH_H; y++) {
      for (let gx = 0; gx < GLYPH_W; gx++) {
        if (glyph[y][gx] === "#") rows[y][x + gx] = true;
      }
    }
    x += GLYPH_W + tracking;
  }
  return rows;
}

/** Grow a matrix by one pixel in all eight directions. */
export function dilate(m: boolean[][]): boolean[][] {
  const h = m.length;
  const w = h ? m[0].length : 0;
  const out = Array.from({ length: h + 2 }, () => new Array<boolean>(w + 2).fill(false));
  for (let y = 0; y < h; y++)
    for (let x = 0; x < w; x++) {
      if (!m[y][x]) continue;
      for (let dy = 0; dy <= 2; dy++) for (let dx = 0; dx <= 2; dx++) out[y + dy][x + dx] = true;
    }
  return out;
}

export function matrixSize(m: boolean[][]): { w: number; h: number } {
  return { h: m.length, w: m.length ? m[0].length : 0 };
}
